xm=getattr(xm,"xc3_model_py",xm)

def offsets(wb,hb):
    """Tegra block-linear offset of every 16-byte block (block height by size, max 16 GOBs)."""
    bh=16
    while bh>1 and hb*1 <= (bh//2)*8: bh//=2
    gw=(wb*16+63)//64
    x=np.arange(wb)*16; y=np.arange(hb)
    X,Y=np.meshgrid(x,y)
    gob=(Y//(8*bh))*gw*512*bh + (X//64)*512*bh + ((Y%(8*bh))//8)*512
    xx=X%64; yy=Y%8
    inner=((xx%64)//32)*256+((yy%8)//2)*64+((xx%32)//16)*32+(yy%2)*16+(xx%16)
    return gob+inner

def footer(d):
    i=d.rfind(b"LBIM"); f=struct.unpack_from("<8I",d,i-36)
    start=i+4-f[0]-4096  # one 4096 byte footer page follows the image data
    return start,f[2],f[3],f[6]

def deswizzle(d):
    start,w,h,fmt=footer(d); assert fmt in (68,77)
    wb,hb=(w+3)//4,(h+3)//4; o=offsets(wb,hb).reshape(-1)
    a=np.frombuffer(d,np.uint8,offset=start)
    return a[o[:,None]+np.arange(16)].reshape(-1),w,h

def dds(blocks,w,h,fmt=77):
    hdr=struct.pack("<4s7I44x",b"DDS ",124,0x81007,h,w,len(blocks),0,1)
    hdr+=struct.pack("<2I4s5I",32,4,b"DX10",0,0,0,0,0)+struct.pack("<5I",0x1000,0,0,0,0)
    hdr+=struct.pack("<5I",{77:98,68:77}[fmt],3,0,1,0)
    return hdr+blocks.tobytes()

args=sys.argv[sys.argv.index("--")+1:]
moddir,origdir,outdir=args
import bpy,os
