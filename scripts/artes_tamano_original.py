os.makedirs(outdir,exist_ok=True)
for name in ["fim_bl_001","fim_bl_002","fim_bl_glow_001","fim_bl_glow_002"]:
    big=open(f"{moddir}/{name}.wilay","rb").read(); orig=bytearray(open(f"{origdir}/{name}.wilay","rb").read())
    blocks,w,h=deswizzle(big)
    p=f"{outdir}/{name}.big.dds"; open(p,"wb").write(dds(blocks,w,h))
    im=bpy.data.images.load(p); im.alpha_mode="STRAIGHT"
    px=np.zeros(w*h*4,np.float32); im.pixels.foreach_get(px); px=px.reshape(h,w,4)[::-1]
    start,ow,oh,fmt=footer(orig)
    k=w//ow; assert (w,h)==(k*ow,k*oh),(w,h,ow,oh)
    small=px.reshape(oh,k,ow,k,4)
    al=small[...,3:]; rgb=(small[...,:3]*al).sum((1,3))/np.maximum(al.sum((1,3)),1e-6)
    out=np.concatenate([rgb,al.mean((1,3))],-1).astype(np.float32)
    if "glow" not in name:  # put the figure where the original one stands
        out=np.roll(out,{"001":-98,"002":51}[name[-3:]],axis=1)
    if "glow" in name:  # silhouette glow generated by glow.py
        gi=bpy.data.images.load(f"{outdir}/glow_{name[-3:]}.png"); gp=np.zeros(ow*oh*4,np.float32)
        gi.pixels.foreach_get(gp); out=gp.reshape(oh,ow,4)[::-1].copy()
    enc=xm.encode_images_rgbaf32([xm.EncodeSurfaceRgba32FloatArgs(ow,oh,1,xm.ViewDimension.D2,{77:xm.ImageFormat.BC7Unorm,68:xm.ImageFormat.BC3Unorm}[fmt],False,np.ascontiguousarray(out).reshape(-1),name,xm.material.TextureUsage.Col)])[0]
    lin=np.frombuffer(bytes(enc.image_data),np.uint8)
    wb,hb=(ow+3)//4,(oh+3)//4; assert len(lin)==wb*hb*16,(len(lin),wb*hb*16)
    o=offsets(wb,hb).reshape(-1)
    a=np.frombuffer(orig,np.uint8,offset=start)
    # preview of the untouched original, to check the swizzle
    ob,_,_=deswizzle(bytes(orig)); open(f"{outdir}/{name}.orig.dds","wb").write(dds(ob,ow,oh,fmt))
    a[o[:,None]+np.arange(16)]=lin.reshape(-1,16)
    open(f"{outdir}/{name}.wilay","wb").write(orig)
    nb,_,_=deswizzle(bytes(orig)); open(f"{outdir}/{name}.new.dds","wb").write(dds(nb,ow,oh,fmt))
    os.remove(p)
    print("ART",name,ow,oh,len(orig))
